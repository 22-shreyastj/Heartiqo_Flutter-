/// Helper/Service class for retrieving location lists.
/// Abstracted so it can be swapped with backend APIs when ready.
class LocationService {
  static List<String> getCountries() {
    return locationData.keys.toList();
  }

  static List<String> getStates(String country) {
    if (country.isEmpty || !locationData.containsKey(country)) {
      return const [];
    }
    return locationData[country]!.keys.toList();
  }

  static List<String> getCities(String country, String state) {
    if (country.isEmpty || state.isEmpty) return const [];
    final countryMap = locationData[country];
    if (countryMap == null || !countryMap.containsKey(state)) return const [];
    return countryMap[state] ?? const [];
  }
}
